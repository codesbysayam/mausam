/**
 * Deterministic label resolver with fallback chain:
 * target lang -> hi -> en -> default English string
 * NEVER returns undefined or raw translation keys.
 */
export function getAlertLabel(
  key: keyof AlertDictionaryLabels,
  langCode: string,
  fallbackLang = 'hi'
): string {
  // 1. Direct match in requested language
  const targetDict = DICTIONARY_MAP[langCode];
  if (targetDict && targetDict[key]) {
    return targetDict[key];
  }

  // 2. Secondary fallback (Hindi)
  const fallbackDict = DICTIONARY_MAP[fallbackLang];
  if (fallbackDict && fallbackDict[key]) {
    return fallbackDict[key];
  }

  // 3. Primary fallback (English)
  if (EN_LABELS[key]) {
    return EN_LABELS[key];
  }

  // 4. Default safety text (should never occur)
  return String(key);
}

